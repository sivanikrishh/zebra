"""Write docs/data_report.md from the GZGC annotations, the masks index and regions.parquet.

    python -m zebrasight.data.report
"""

from __future__ import annotations

import pandas as pd

from zebrasight.config import REPO_ROOT
from zebrasight.data import gzgc
from zebrasight.data.masks import INDEX, RULE
from zebrasight.data.regions import MIN_REGION_PX, OUT as REGIONS, check_splits

DOC = REPO_ROOT / "docs" / "data_report.md"


def _md(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines)


def render() -> str:
    df = gzgc.load_annotations()
    sub = gzgc.left_subset(df)
    sub["split"] = gzgc.assign_splits(sub)
    vp = df.viewpoint.value_counts().rename_axis("viewpoint").reset_index(name="annotations")
    sightings = df.groupby("zebra_id").size()
    dates = df.groupby("date").agg(annotations=("ann_id", "size"), zebras=("zebra_id", "nunique")).reset_index()
    cm = sub.cm_per_px.quantile([0.0, 0.1, 0.5, 0.9, 1.0]).round(3)
    per_zebra = sub.groupby("zebra_id").agg(views=("ann_id", "size"), dates=("date", "nunique"))
    split = sub.groupby("split").agg(views=("ann_id", "size"), zebras=("zebra_id", "nunique"),
                                     encounters=("encounter_id", "nunique"), sessions=("session_id", "nunique"))

    masks_txt = "_Masks not built yet._"
    if INDEX.exists():
        idx = pd.read_parquet(INDEX)
        mm = idx.mask_method.value_counts().rename_axis("mask_method").reset_index(name="annotations")
        iou = idx.loc[idx.mask_method == "maskrcnn_rule", "mask_iou"].describe().round(2)
        masks_txt = (f"{_md(mm)}\n\nMatched Mask R-CNN masks: IoU with the annotation box median {iou['50%']}, "
                     f"range {iou['min']}–{iou['max']}.")
    regions_txt = "_regions.parquet not built yet._"
    if REGIONS.exists():
        reg = pd.read_parquet(REGIONS)
        rs = reg.groupby(["region", "split"]).size().unstack(fill_value=0).reset_index()
        ck = check_splits(reg)
        regions_txt = (f"`data/regions.parquet`: {len(reg)} rows (image × region; a region needs ≥ {MIN_REGION_PX} px).\n\n"
                       f"{_md(rs)}\n\nSplit check: {ck['encounters_in_both_splits']} encounters in both splits; "
                       f"{ck['zebras_with_gallery_and_query']} of {ck['zebras']} zebras have gallery and query regions.")

    return f"""# Data report: GZGC (Wild Me GZGC-IBEIS)

Generated by `python -m zebrasight.data.report`.

## Source and licence

- Wild Me **GZGC-IBEIS** (Great Zebra and Giraffe Count, Nairobi National Park, Feb–Mar 2015),
  COCO format, organiser-provided archive `data/raw/gzgc.coco.tar.gz` (10,433,199,738 bytes),
  unpacked to `data/raw/gzgc/` (4,948 JPEGs, 10.45 GB; 3 annotation JSONs, only `train2020` populated).
- **Licence: CC BY-NC-ND 2.0** (Attribution, NonCommercial, NoDerivatives).
  Every image we derive (masks, percepts, QA grids, VR textures) is **internal – not for public
  display** until use of derived images is confirmed. Charts of statistics are fine.

## Whole dataset (plains zebra only)

- {len(df)} zebra annotations in {df.image_id.nunique()} images; {df.zebra_id.nunique()} named individuals
  (`name` → `zebra_id`); {df.session_id.nunique()} sessions (date × car × person, parsed from the
  `photographer` field; {int((df.session_id.str.endswith('_unknown')).sum())} annotations have no photographer → `<date>_unknown`).
- Sightings per individual: median {int(sightings.median())}, {int((sightings >= 2).sum())} individuals with ≥ 2,
  {int((sightings >= 5).sum())} with ≥ 5.

{_md(vp)}

{_md(dates)}

## Subset used: left-side views, ≥ 2 dates

Every zebra with **≥ 2 left-side views on different dates** (viewpoint exactly `left`, known date);
all its left views are kept. Face (left side of the head) and flank come from the same left photo,
linked by `zebra_id`.

- **{sub.zebra_id.nunique()} individuals**, {len(sub)} left views, {sub.image_id.nunique()} images,
  {sub.encounter_id.nunique()} encounters, {sub.session_id.nunique()} sessions.
- Views per zebra: median {int(per_zebra.views.median())}, range {per_zebra.views.min()}–{per_zebra.views.max()};
  dates per zebra: {per_zebra.dates.value_counts().sort_index().to_dict()}.
- Rotated annotation boxes (theta ≠ 0): {int((sub.theta != 0).sum())}; the axis-aligned COCO box is used.

### Gallery / query split

Per zebra, **gallery = its encounters on its earliest date, query = encounters on later dates**.
Sessions are day-bound, so no encounter (zebra × session) is ever in both splits.

{_md(split.reset_index())}

## Scale (grade C)

`cm_per_px = {gzgc.BODY_LENGTH_CM:.1f} cm / bbox width`, side views only; `cm_per_px_unc = {gzgc.CM_PER_PX_UNC}`;
`scale_method = "{gzgc.SCALE_METHOD}"`.
Plains zebra head–body length 217–246 cm (midpoint used), as reported by GBIF and Wikipedia and
attributed to Grubb (1981) *Equus burchelli*, Mammalian Species 157:1–9. **UNVERIFIED**: primary
text not seen, and two different DOIs are cited (10.2307/3504012, 10.2307/3503962).
The box spans nose to rump only when the animal stands broadside with its head up; head-down
grazing and slight obliques change the width, hence ±20%.

cm_per_px over the subset (quantiles 0/10/50/90/100%): {cm.tolist()}.

## Masks and regions

Mask R-CNN (torchvision ResNet-50 FPN v2, COCO weights, class "zebra"), matched to each
annotation box by IoU ≥ 0.5; fallback = whole box. Rule split (grade C), head on the image left for
left views: face = front {int(RULE['face'][1] * 100)}% of the mask length, flank = {int(RULE['flank'][0] * 100)}–{int(RULE['flank'][1] * 100)}%,
rump = rear {int((1 - RULE['rump'][0]) * 100)}%, all within the upper {int(RULE['body_band'] * 100)}% of the mask height (legs dropped).
QA grid: `docs/examples/masks/qa_grid.png` (internal).

{masks_txt}

{regions_txt}

### Known issues from the QA grid (grade C, for the limits slide)

- **Head-down grazing:** the face rule (front 20%, upper 65%) catches only part of a lowered head.
- **Overlapping zebras:** when a neighbour's head or body overlaps the front of the box, the face
  region can contain the other animal.
- **bbox_rule fallbacks** (no Mask R-CNN match): regions are box strips and include background
  (grass, sky). Filter with `mask_method == "maskrcnn_rule"` when that matters.
- The tail is part of the mask and lands in the rump region.
"""


if __name__ == "__main__":
    DOC.write_text(render(), encoding="utf-8")
    print(f"wrote {DOC}")

"""Render docs/calibration.md from the results dict (re-run: python -m zebrasight.calibration.report)."""

from __future__ import annotations

import json

import numpy as np

from zebrasight.config import REPO_ROOT


def _table(rows, with_melin=True) -> str:
    out = ["| Species | Stripe | Width (cm) | Light | Ours (m) | Melin (m) | Ours / Melin |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        ratio = r["ours_m"] / r["melin_m"]
        out.append(f"| {r['species']} | {r['stripe']} | {r['width_cm']:.2f} | {r['light']} | {r['ours_m']:.2f} | "
                   f"{r['melin_m']:.2f} | {ratio:.3f} ({100 * (ratio - 1):+.1f}%) |")
    return "\n".join(out)


def _by_light(rows) -> str:
    out = ["| Light | mean ours / Melin | min | max |", "|---|---|---|---|"]
    for light in ("day", "dusk", "night"):
        r = [x["ours_m"] / x["melin_m"] for x in rows if x["light"] == light]
        out.append(f"| {light} | {np.nanmean(r):.3f} | {np.nanmin(r):.3f} | {np.nanmax(r):.3f} |")
    return "\n".join(out)


def render(res: dict) -> str:
    ao = res["acuity_only"]
    n_pass = sum(abs(r["err_pct"]) <= 5.0 for r in ao)
    errs = [r["err_pct"] for r in ao]
    chk = res["acuity_check"]
    av = res["acuityview"]
    v = res["variants"]
    mtf_rows = "\n".join(f"| {r:.2f} | {o:.4f} | {t:.4f} |" for r, o, t in av["mtf"])
    img_rows = "\n".join(
        f"| {k.replace('period_', '').replace('px', ' px')} ({x['cpd']:.1f} cpd) | {x['rms_contrast_ours']:.4f} | "
        f"{x['rms_contrast_acuityview']:.4f} | {x['rmse_rel_mean']:.4f} |"
        for k, x in av.items() if k.startswith("period_"))
    variant_rows = "\n".join(
        f"| {name} | {np.nanmean([r['ours_m'] / r['melin_m'] for r in rows]):.3f} | "
        f"{np.nanmin([r['ours_m'] / r['melin_m'] for r in rows]):.3f} | "
        f"{np.nanmax([r['ours_m'] / r['melin_m'] for r in rows]):.3f} |"
        for name, rows in v.items())
    full_name = [k for k in v if k.startswith("full")][0]

    return f"""# Calibration: ZebraEye vs Melin et al. 2016 Table 2

Generated by `python -m zebrasight.calibration.melin` ({res['runtime_s']:.0f} s on the RTX 3050).
Raw numbers: `docs/calibration_results.json`. Figure: `docs/figures/calibration.png`.

## What this shows (and what it does not)

Melin's Table 2 distances follow from the acuity formula `d = 2w / tan(1/A)`; they are not
behavioural measurements. Matching them shows that **our filter's cut-off sits at the
published resolution limit** — a calibration of the implementation, not an independent
validation of the zebra eye (see docs/eye_parameters.md).

## Method

- Pipeline: geometry + dichromacy + streak (acuity map; field position 0,0) + CSF in `peli`
  mode. Motion and noise off. Linear-light black/white square-wave grating, 100% Michelson
  contrast, stripe width w (period 2w), 40 source px per period, 60 periods, 6 periods tall.
- Light levels: day = c0 (16 cd/m², 23.30 cpd), dusk = c8 (0.16 cd/m², 12.46 cpd),
  night = c9 (1.6e-5 cd/m², rod only, 1.61 cpd).
- Distance swept in 1% steps (d = d_Melin × 1.01^k, k = +15 … −40), scanning from far to near.
  Detection distance = the largest distance at which the output contrast of the grating
  fundamental in the central region (Hann-weighted least-squares fit at the known frequency,
  per row) exceeds 1e-3.
- Pass criterion: within 5% of Melin.

## 1. Acuity-only calibration: {n_pass}/{len(ao)} within 5% (1% distance steps)

{_table(ao)}

Error range {min(errs):+.1f}% to {max(errs):+.1f}% (mean {np.mean(errs):+.1f}%).

{_by_light(ao)}

**Why ours is slightly longer than Melin.** Melin's distance is where the stripe period equals
1/A exactly. Our filter keeps the fundamental up to A·(1 + `csf.cutoff_taper`) = 1.02 A (a
raised-cosine roll-off, needed so a grating exactly at A is not lost between FFT bins), and a
square wave's fundamental has contrast 4/π = 1.27, so it is still above threshold just past A.
Both push detection 1–3% beyond Melin; they are inside the 5% tolerance and in the
expected direction.

## 2. Day acuity check (50 m, full contrast)

| Grating | Output contrast at the grating frequency | Verdict |
|---|---|---|
| 23.3 cpd | {chk['23.3']:.2e} | {'visible' if chk['23.3'] > 1e-3 else 'NOT visible'} |
| 26.0 cpd | {chk['26.0']:.2e} | {'gone' if chk['26.0'] <= 1e-3 else 'STILL VISIBLE'} |

## 3. AcuityView cross-check (Caves & Johnsen 2018)

AcuityView's MTF, read from the package source, is `exp(-3.56 (R f)^2)` with R the minimum
resolvable angle in degrees (= 1/A) and f in cycles/degree (radial frequency rounded to whole
cycles per image); implementation in `zebrasight/calibration/acuityview.py`.
Our acuity-only filter is the CSF transfer H(f): 1 up to b = 0.1 A, then S(f)/c, zero beyond 1.02 A.

| f / A | ours H(f) | AcuityView MTF |
|---|---|---|
{mtf_rows}

On a full-contrast wavy coat (512 × 512, 0.01 deg/px, A = 23.3 cpd):

| Stripe period | RMS contrast, ours | RMS contrast, AcuityView | RMS difference / mean |
|---|---|---|---|
{img_rows}

**Difference.** Both filters put the resolution limit at the acuity (AcuityView passes 2.8%
there, ours 2%). They differ below it: ours follows the CSF shape, so mid frequencies
(0.25–0.75 A) are attenuated much more than in AcuityView's Gaussian, while AcuityView keeps a
small tail above A (0.4% at 1.25 A) that ours removes. AcuityView is an acuity (optical blur)
model only; ours adds contrast sensitivity, which is why stripes well inside the acuity limit
lose more contrast in our percept. Neither model applies a contrast threshold here.

## 4. Figure

![ZebraEye vs Melin et al. 2016](figures/calibration.png)

Output contrast of the 5.23 cm plains flank stripe versus distance, one line per light level;
dotted verticals at Melin's 139.64 / 74.67 / 9.65 m; dashed horizontal = detection threshold.

## 5. Full eye: how much shorter?

Realistic stimuli: stripe contrast 0.6 (linear Michelson), wavy stripes (rows shifted by
0.15 period × sin(2π y / 3 periods), tilt ≤ 17°), then the full eye (motion stage on but static,
streak, Peli CSF, photon + neural noise). Distance found by **bisection** on log distance to 1%
(bracket 0.3–1.15 × Melin, widened if needed). With noise, each step runs 5 noise seeds in
one batch (each image gets its own seed). Detection = median contrast over the 5 seeds >
max(1e-3, 3 × the median of the same measurement on a uniform field at the grating's mean
level, also over 5 seeds). Bisection assumes detection is monotonic in distance. Round 1 is
monotonic (see figure); with noise the 5-seed median keeps it close to monotonic.

| Stimulus | mean ours / Melin | min | max |
|---|---|---|---|
{variant_rows}

Per entry, {full_name}:

{_table(v[full_name])}

Melin's distances are acuity-only: they assume full-contrast stripes and no noise. Real
stripes (contrast 0.6, wavy) with photon and neural noise are lost earlier; the CSF's
contrast threshold, not the acuity, then sets the limit.
"""


if __name__ == "__main__":
    res = json.loads((REPO_ROOT / "docs" / "calibration_results.json").read_text(encoding="utf-8"))
    (REPO_ROOT / "docs" / "calibration.md").write_text(render(res), encoding="utf-8")
